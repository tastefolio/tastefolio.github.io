// Copies the shared runtime into every skill and regenerates each skill's stack-adapter reference
// from its tokens.css, so every skill folder stays self-contained.
import { readFile, writeFile, mkdir, readdir, copyFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const SKILLS = join(ROOT, 'skills');

export async function listSkills() {
  const dirs = (await readdir(SKILLS, { withFileTypes: true })).filter((d) => d.isDirectory()).map((d) => d.name);
  return dirs.filter((d) => existsSync(join(SKILLS, d, 'SKILL.md'))).sort();
}

/** Returns the custom properties declared in the first `:root {…}` block of a tokens file. */
export function rootTokens(css) {
  const m = css.match(/:root[^{]*\{([\s\S]*?)\n\}/);
  if (!m) return [];
  return [...m[1].matchAll(/(--[\w-]+)\s*:/g)].map((x) => x[1]);
}

const groups = [
  ['color', (t) => /^--(canvas|surface|ink|line|brand|accent|focus|success|warning|danger|info|overlay|highlight|chart|led|dot$)/.test(t)],
  ['font', (t) => t.startsWith('--font-')],
  ['text', (t) => t.startsWith('--fs-')],
  ['radius', (t) => t.startsWith('--radius')],
  ['shadow', (t) => t.startsWith('--shadow')],
  ['spacing', (t) => t.startsWith('--space-')],
];

function adapters(name, title, tokens) {
  const by = Object.fromEntries(groups.map(([g, test]) => [g, tokens.filter(test)]));
  const tw4 = [
    ...by.color.map((t) => `  --color-${t.slice(2)}: var(${t});`),
    ...by.font.map((t) => `  --font-${t.slice(7)}: var(${t});`),
    ...by.text.map((t) => `  --text-${t.slice(5)}: var(${t});`),
    ...by.radius.map((t) => `  --radius-${t.replace(/^--radius-?/, '') || 'DEFAULT'}: var(${t});`),
    ...by.shadow.map((t) => `  --shadow-${t.replace(/^--shadow-?/, '') || 'DEFAULT'}: var(${t});`),
    ...by.spacing.map((t) => `  --spacing-${t.slice(8)}: var(${t});`),
  ].join('\n');
  const tw3colors = by.color.map((t) => `        '${t.slice(2)}': 'var(${t})',`).join('\n');
  const has = (t) => tokens.includes(t);
  const pick = (...c) => c.find(has) || c[c.length - 1];
  const shad = [
    ['--background', '--canvas'], ['--foreground', '--ink'],
    ['--card', pick('--surface', '--canvas')], ['--card-foreground', '--ink'],
    ['--popover', pick('--surface-raised', '--surface')], ['--popover-foreground', '--ink'],
    ['--primary', '--brand'], ['--primary-foreground', '--brand-ink'],
    ['--secondary', pick('--surface-2', '--surface')], ['--secondary-foreground', '--ink'],
    ['--muted', pick('--surface-2', '--surface')], ['--muted-foreground', pick('--ink-2', '--ink')],
    ['--accent', pick('--brand-soft', '--surface-2')], ['--accent-foreground', pick('--brand-strong', '--ink')],
    ['--destructive', '--danger'], ['--border', '--line'], ['--input', pick('--line-2', '--line')], ['--ring', '--focus'],
    ['--radius', pick('--radius-md', '--radius')],
    ...[1, 2, 3, 4, 5].filter((i) => has(`--chart-${i}`)).map((i) => [`--chart-${i}`, `--chart-${i}`]),
    ['--sidebar', pick('--surface', '--canvas')], ['--sidebar-foreground', '--ink'], ['--sidebar-primary', '--brand'],
    ['--sidebar-primary-foreground', '--brand-ink'], ['--sidebar-accent', pick('--surface-2', '--surface')],
    ['--sidebar-accent-foreground', '--ink'], ['--sidebar-border', '--line'], ['--sidebar-ring', '--focus'],
  ].filter(([a, b]) => a !== b).map(([a, b]) => `  ${a}: var(${b});`).join('\n');

  return `<!-- Generated by scripts/sync.mjs from assets/tokens.css — edit tokens.css, not this file. -->
# Stack adapters — ${title}

\`assets/tokens.css\` is the single source of truth (light + dark + Persian/RTL overrides).
Keep the token **names** when porting; change **values** only through the brand rules in \`SKILL.md\`.

## 1. Plain HTML / any framework

\`\`\`html
<link rel="stylesheet" href="tokens.css">
<link rel="stylesheet" href="kit.css">   <!-- optional reference components -->
<script src="kit.js" defer></script>      <!-- optional behaviors: tabs, menus, dialogs, filters, charts -->
\`\`\`

Set \`<html lang="en" dir="ltr">\` or \`<html lang="fa" dir="rtl">\`; dark mode is \`<html data-theme="dark">\`.

## 2. Tailwind CSS v4

\`\`\`css
@import "tailwindcss";
@import "./tokens.css";

@custom-variant dark (&:where([data-theme=dark], [data-theme=dark] *));

@theme inline {
${tw4}
}
\`\`\`

Then write \`bg-canvas text-ink border-line\`, \`bg-brand text-brand-ink\`, \`font-display\`, \`rounded-md\`.
Never use Tailwind's default palette (\`bg-blue-500\`, \`text-gray-600\`…) next to these tokens — it breaks the style.

## 3. Tailwind CSS v3

\`\`\`js
// tailwind.config.js
export default {
  darkMode: ['selector', '[data-theme="dark"]'],
  theme: {
    extend: {
      colors: {
${tw3colors}
      },
      fontFamily: { ${by.font.map((t) => `'${t.slice(7)}': 'var(${t})'`).join(', ')} },
      borderRadius: { ${by.radius.map((t) => `'${t.replace(/^--radius-?/, '') || 'DEFAULT'}': 'var(${t})'`).join(', ')} },
    },
  },
};
\`\`\`

## 4. shadcn/ui (or any library that reads the same variables)

Add after \`tokens.css\` in \`globals.css\`. The same block works for dark mode because the source tokens switch.

\`\`\`css
:root, [data-theme="dark"] {
${shad}
}
\`\`\`

Mapping colors is only half of the job: also apply **Component library overrides** from \`SKILL.md\`
(radius, borders, shadows, density, focus style). A shadcn default look with ${title} colors is *not* ${title}.

## 5. Native apps / design tools

Copy hex values from the \`:root\` (light) and \`[data-theme="dark"]\` blocks of \`tokens.css\`.
Spacing, radius and type values are plain px/rem and translate 1:1 to dp/pt.

## Token inventory

${groups.map(([g]) => (by[g].length ? `- **${g}**: ${by[g].map((t) => `\`${t}\``).join(', ')}` : '')).filter(Boolean).join('\n')}
`;
}

export async function sync({ quiet = false } = {}) {
  const kit = join(ROOT, 'shared', 'kit.js');
  const skills = await listSkills();
  for (const s of skills) {
    const dir = join(SKILLS, s);
    await mkdir(join(dir, 'assets'), { recursive: true });
    await mkdir(join(dir, 'references'), { recursive: true });
    await copyFile(kit, join(dir, 'assets', 'kit.js'));
    const tokensPath = join(dir, 'assets', 'tokens.css');
    if (existsSync(tokensPath)) {
      const css = await readFile(tokensPath, 'utf8');
      const meta = existsSync(join(dir, 'meta.json')) ? JSON.parse(await readFile(join(dir, 'meta.json'), 'utf8')) : { name: s };
      await writeFile(join(dir, 'references', 'adapters.md'), adapters(s, meta.name || s, rootTokens(css)));
    }
  }
  await writeMarketplace(skills);
  await writeReadmes(skills);
  if (!quiet) console.log(`synced ${skills.length} skills`);
  return skills;
}

